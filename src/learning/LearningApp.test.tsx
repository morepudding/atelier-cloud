// @vitest-environment jsdom
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { cleanup, render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { App } from '../App';
import { initialState } from '../domain/engine';
import { STORAGE_KEY } from '../domain/scenario';
import { deserializeLearning, LEARNING_KEY } from './persistence';
import { reasons, predictions } from './teaching';

beforeEach(() => { localStorage.clear(); window.history.replaceState(null, '', '/'); });
afterEach(cleanup);
const coach = () => within(screen.getByRole('complementary', { name: 'Accompagnement de Nora' }));
const saved = () => deserializeLearning(localStorage.getItem(LEARNING_KEY)).state;
const userButton = (user: ReturnType<typeof userEvent.setup>, name: string) => user.click(screen.getByRole('button', { name }));
async function readyFor(user: ReturnType<typeof userEvent.setup>, label: string) {
  await waitFor(() => expect((screen.getByRole('button', { name: label }) as HTMLButtonElement).disabled).toBe(false), { timeout: 3000 });
  await userButton(user, label);
}
async function startAndVerify(user: ReturnType<typeof userEvent.setup>) {
  await userButton(user, 'Démarrer');
  await waitFor(() => expect((screen.getByRole('button', { name: 'Arrêter' }) as HTMLButtonElement).disabled).toBe(false), { timeout: 3000 });
  await userButton(user, 'Parcourir');
}
describe('Un enseignement jouable avec un monde et des preuves séparés', () => {
  it('enseigne, démontre, corrige une prédiction, accompagne une expérience puis reconnaît un autre cas autonome', async () => {
    const user = userEvent.setup();
    render(<App />);
    expect(screen.getByRole('region', { name: 'Portail Azure' })).toBeTruthy();
    await userButton(user, 'Comprendre avant d’essayer');
    expect(coach().getByRole('heading', { name: 'Où tourne l’application ?' })).toBeTruthy();
    expect(coach().getByText(/Un groupe seul n’exécute pas une application/)).toBeTruthy();
    await userButton(user, 'Voir Nora faire l’expérience');
    await userButton(user, 'Ouvrir l’application d’exemple');
    expect(screen.getByText('Version 1.0.0')).toBeTruthy();
    await userButton(user, 'Voir l’arrêt du service');
    await readyFor(user, 'Observer le site après l’arrêt');
    expect(screen.getByRole('heading', { name: /Error 403/ })).toBeTruthy();
    await userButton(user, 'Voir la remise en service');
    await readyFor(user, 'Vérifier le retour du site');
    expect(screen.getByText('Version 1.0.0')).toBeTruthy();
    expect(saved().world.apps[0].status).toBe('running');
    expect(saved().evidence).toHaveLength(0);
    await userButton(user, 'À mon tour');
    await user.click(coach().getByLabelText(predictions[1].label));
    await userButton(user, 'Comparer avec l’exemple');
    expect(coach().getByRole('status').textContent).toContain('ne prend pas le relais');
    await user.click(coach().getByLabelText(predictions[0].label));
    await userButton(user, 'Comparer avec l’exemple');
    await userButton(user, 'Passer à l’expérience');
    await userButton(user, 'Arrêter');
    await waitFor(() => expect(screen.getByText('Arrêtée', { selector: '.badge' })).toBeTruthy(), { timeout: 3000 });
    await userButton(user, 'Parcourir');
    expect(screen.getByRole('heading', { name: /Error 403/ })).toBeTruthy();
    await userButton(user, 'Revenir à la Web App');
    await startAndVerify(user);
    expect(screen.getByText('Version 1.4.2')).toBeTruthy();
    await userButton(user, 'Faire le point sur l’expérience');
    await user.click(coach().getByLabelText(reasons[0].label));
    await userButton(user, 'Vérifier mon explication');
    expect(coach().getByText('Expérience réalisée avec aide')).toBeTruthy();
    await userButton(user, 'Un autre problème, à moi');
    expect(screen.getByRole('heading', { name: /Error 403/ })).toBeTruthy();
    await userButton(user, 'Revenir au portail Azure');
    expect(screen.getByRole('heading', { name: 'App Services' })).toBeTruthy();
    await user.click(screen.getByRole('button', { name: 'app-interventions-dev-1' }));
    await startAndVerify(user);
    expect(screen.getByText('Version 2.1.0')).toBeTruthy();
    await user.click(coach().getByLabelText(reasons[0].label));
    await userButton(user, 'Vérifier mon intervention');
    expect(coach().getByText('Démontré en autonomie sur ce cas')).toBeTruthy();
    expect(coach().getByText('Réalisé avec aide')).toBeTruthy();
    expect(coach().getByText('Non abordé dans ce mini-parcours')).toBeTruthy();
    expect(saved().evidence).toHaveLength(2);
    expect(screen.getAllByRole('complementary', { name: 'Accompagnement de Nora' })).toHaveLength(1);
  }, 25000);
  it('conserve les indices et l’essai après remontage et qualifie honnêtement sa résolution', async () => {
    const user = userEvent.setup();
    const view = render(<App />);
    await userButton(user, 'Je connais déjà, essayer un cas');
    await userButton(user, 'Un indice');
    expect(coach().getByText('Essai accompagné')).toBeTruthy();
    view.unmount();
    render(<App />);
    expect(coach().getByText(/Compare ce que montre le navigateur/)).toBeTruthy();
    await userButton(user, 'Revenir au portail Azure');
    await userButton(user, 'app-interventions-dev-1');
    await startAndVerify(user);
    await user.click(coach().getByLabelText(reasons[0].label));
    await userButton(user, 'Vérifier mon intervention');
    expect(coach().getByText('Réalisé avec aide')).toBeTruthy();
    expect(coach().queryByText('Démontré en autonomie sur ce cas')).toBeNull();
    await userButton(user, 'Essayer un nouveau cas');
    expect(coach().getByText('Sans indice demandé')).toBeTruthy();
    expect(saved().world.apps[1].name).toBe('app-annuaire-dev-2');
    const address = screen.getByRole('textbox', { name: 'Adresse du navigateur' });
    expect((address as HTMLInputElement).value).toBe('https://app-annuaire-dev-2.azurewebsites.net');
    await user.click(address);
    await user.keyboard('{Enter}');
    expect(saved().response?.address).toBe('https://app-annuaire-dev-2.azurewebsites.net');
    expect(screen.getByRole('heading', { name: /Error 403/ })).toBeTruthy();
  }, 12000);
  it('préserve la sauvegarde de l’ancien exercice et permet de passer de l’un à l’autre', async () => {
    const old = initialState();
    old.run.teacherIntroStep = 3;
    old.run.draft.name = 'mon-groupe-en-cours';
    old.notes = 'Mes anciennes notes';
    const raw = JSON.stringify(old);
    localStorage.setItem(STORAGE_KEY, raw);
    const user = userEvent.setup();
    render(<App />);
    expect(localStorage.getItem(STORAGE_KEY)).toBe(raw);
    await userButton(user, 'Comprendre avant d’essayer');
    await userButton(user, 'Options du parcours');
    await userButton(user, 'Reprendre l’ancien exercice');
    expect(screen.getByRole('complementary', { name: 'Accompagnement de la mission' })).toBeTruthy();
    expect(localStorage.getItem(STORAGE_KEY)).toBe(raw);
    await userButton(user, 'Options de la mission');
    await userButton(user, 'Nouveau parcours · Application indisponible');
    expect(coach().getByRole('heading', { name: 'Où tourne l’application ?' })).toBeTruthy();
    expect(localStorage.getItem(STORAGE_KEY)).toBe(raw);
  });
  it('garde la réduction et le carnet lors des changements de surface et d’un rechargement', async () => {
    const user = userEvent.setup();
    const view = render(<App />);
    await userButton(user, 'Options du parcours');
    await userButton(user, 'Ouvrir le carnet');
    await user.type(screen.getByLabelText('Mes observations et mes explications'), 'Le code reste en place.');
    await userButton(user, 'Réduire l’encadré de Nora');
    await userButton(user, 'Ouvrir Microsoft Azure');
    expect(screen.getByRole('region', { name: 'Portail Azure' })).toBeTruthy();
    view.unmount();
    render(<App />);
    expect(screen.getByRole('button', { name: 'Développer l’encadré de Nora' })).toBeTruthy();
    expect(saved().notes).toBe('Le code reste en place.');
  });
  it('conserve à part une sauvegarde V2 illisible et garde l’ancien exercice intact', () => {
    localStorage.setItem(LEARNING_KEY, 'broken-save');
    localStorage.setItem(STORAGE_KEY, 'old-course-data');
    render(<App />);
    expect(screen.getByRole('alert').textContent).toContain('conservée à part');
    expect(localStorage.getItem(LEARNING_KEY + '.recovery')).toBe('broken-save');
    expect(localStorage.getItem(STORAGE_KEY)).toBe('old-course-data');
  });
});
